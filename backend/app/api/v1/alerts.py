"""Alerts API router for DataSentinel 2.0.

Endpoints:
- GET  /api/v1/alerts
- GET  /api/v1/alerts/{alert_id}
- POST /api/v1/alerts (Ingestion hook for Person 1 PySpark Engine)
"""

from typing import Optional
from fastapi import APIRouter, HTTPException, Query, status

from app.persistence.repository import Repository
from app.schemas.alerts import AlertCreate, AlertListResponse, AlertRead

router = APIRouter()


@router.get(
    "",
    response_model=AlertListResponse,
    summary="List alerts with pagination and filtering",
    description="Retrieves security anomaly alerts generated by PySpark or network sensors.",
)
async def list_alerts(
    skip: int = Query(0, ge=0, description="Offset index for pagination"),
    limit: int = Query(50, ge=1, le=200, description="Page size limit"),
    severity: Optional[str] = Query(None, description="Filter by severity: low, medium, high, critical"),
    status_filter: Optional[str] = Query(None, alias="status", description="Filter by status: OPEN, INVESTIGATING, RESOLVED, CLOSED"),
) -> AlertListResponse:
    alerts, total = Repository.list_alerts(
        skip=skip,
        limit=limit,
        severity=severity,
        status=status_filter,
    )
    items = [AlertRead(**a) for a in alerts]
    return AlertListResponse(items=items, total=total, skip=skip, limit=limit)


@router.get(
    "/{alert_id}",
    response_model=AlertRead,
    summary="Get alert details",
    description="Fetch full attributes, anomaly score, and telemetry context for a specific alert.",
)
async def get_alert(alert_id: str) -> AlertRead:
    alert = Repository.get_alert(alert_id)
    if not alert:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Alert with ID '{alert_id}' was not found.",
        )
    return AlertRead(**alert)


@router.post(
    "",
    response_model=AlertRead,
    status_code=status.HTTP_201_CREATED,
    summary="Ingest a new security alert",
    description="Allows Person 1's PySpark anomaly detection pipeline or external collectors to register alerts.",
)
async def create_alert(payload: AlertCreate) -> AlertRead:
    data = payload.model_dump()
    if not data.get("id"):
        from uuid import uuid4
        data["id"] = f"alert-{uuid4().hex[:8]}"
    created = Repository.create_alert(data)
    return AlertRead(**created)
